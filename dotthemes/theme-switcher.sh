#!/usr/bin/env bash
# ╔══════════════════════════════════════════════════════════╗
# ║               theme-switch  —  vanta palette             ║
# ╚══════════════════════════════════════════════════════════╝
#
# USAGE
#   ./theme-switch.sh              # interactive picker
#   ./theme-switch.sh "Cyber Cyan" # apply directly

# ┌─────────────────────────────────────────────────────────┐
# │  PATHS — set these before running                       │
# └─────────────────────────────────────────────────────────┘
KITTY_CONF="$HOME/.config/kitty/color.conf"        # e.g. "$HOME/.config/kitty/color.conf"
NVIM_LUA="$HOME/.config/nvim/lua/colors.lua"          # e.g. "$HOME/.config/nvim/lua/colors.lua"
GTK_CSS="$HOME/.config/waybar/colors/colors.css"           # e.g. "$HOME/.config/gtk-3.0/colors.css"
JSON_SRC="$(dirname "$0")/colors.json"

# ── preflight checks ───────────────────────────────────────
command -v python3 &>/dev/null || { echo "error: python3 is required"; exit 1; }

for var in KITTY_CONF NVIM_LUA GTK_CSS; do
  [[ -z "${!var}" ]] && {
    echo "error: \$$var is not set — edit the PATHS section at the top of this script"
    exit 1
  }
done

[[ -f "$JSON_SRC" ]] || { echo "error: colors.json not found at '$JSON_SRC'"; exit 1; }

# ── load all palettes into ROWS array via python3 ──────────
# each row: "Palette Name|#bg|#base|#surface|#overlay|#border|#subtext|#text|#bright|#accent|#dim"
mapfile -t ROWS < <(python3 - "$JSON_SRC" <<'PY'
import json, sys
data = json.load(open(sys.argv[1]))
keys = ["true_black","vanta_ui","surface","elevated","border",
        "muted_text","body_text","bright_text","accent","accent_dim"]
for p in data:
    c = p["colors"]
    print(p["palette"] + "|" + "|".join(c[k]["hex"] for k in keys))
PY
)

NAMES=()
for row in "${ROWS[@]}"; do
  IFS='|' read -r name _ <<< "$row"
  NAMES+=("$name")
done

# ── ANSI true-colour helpers ───────────────────────────────
RST=$'\033[0m'
BOLD=$'\033[1m'

hex_bg() {                          # $1 = #rrggbb
  local h="${1#\#}"
  local r=$(( 16#${h:0:2} ))
  local g=$(( 16#${h:2:2} ))
  local b=$(( 16#${h:4:2} ))
  printf $'\033[48;2;%d;%d;%dm' "$r" "$g" "$b"
}

swatch() { printf "%s  ${RST}" "$(hex_bg "$1")"; }   # filled 2-space block

# ── interactive picker (list first, then selector) ─────────
pick_theme() {
  # First, show numbered list of themes
  echo ""
  printf "${BOLD}Available Themes:${RST}\n"
  printf "%s\n" "──────────────────────────────────────────────────────────────"
  
  for i in "${!NAMES[@]}"; do
    printf "  ${BOLD}%3d${RST}  %s\n" "$((i+1))" "${NAMES[$i]}"
  done
  
  printf "%s\n" "──────────────────────────────────────────────────────────────"
  echo ""

  # Then show the color preview
  printf "${BOLD}Color Preview:${RST}\n"
  printf "  %-4s %-22s %s\n" \
    "#" "palette" "← dark backgrounds ——————  text tones ———  accent"
  printf "  %s\n" "──────────────────────────────────────────────────────────────"

  for i in "${!ROWS[@]}"; do
    IFS='|' read -r name bg base surf over brd sub txt brt acc dim <<< "${ROWS[$i]}"
    printf "  ${BOLD}%-4s${RST}%-22s" "$((i+1))" "$name"
    swatch "$bg"; swatch "$base"; swatch "$surf"; swatch "$over"; swatch "$brd"
    printf "  "
    swatch "$sub"; swatch "$txt"; swatch "$brt"
    printf "  "
    swatch "$acc"; swatch "$dim"
    printf "\n"
  done

  printf "  %s\n" "──────────────────────────────────────────────────────────────"
  echo ""

  # Finally, get user input
  local choice
  while true; do
    read -rp "  Select a theme by number (1-${#NAMES[@]}): " choice
    [[ "$choice" =~ ^[0-9]+$ ]] \
      && (( choice >= 1 && choice <= ${#NAMES[@]} )) \
      && break
    echo "  ↳ please enter a number between 1 and ${#NAMES[@]}"
  done
  printf "%s" "${NAMES[$((choice-1))]}"
}

# ── resolve theme ──────────────────────────────────────────
if [[ -n "$1" ]]; then
  THEME="$1"
  match=0
  for n in "${NAMES[@]}"; do [[ "$n" == "$THEME" ]] && match=1 && break; done
  (( match )) || { echo "error: theme '$THEME' not found in $JSON_SRC"; exit 1; }
else
  THEME=$(pick_theme)
fi

# ── extract chosen palette's colours ──────────────────────
for row in "${ROWS[@]}"; do
  IFS='|' read -r name bg base surface overlay border \
                      subtext text bright accent muted <<< "$row"
  [[ "$name" == "$THEME" ]] && break
done

printf "\n  applying ${BOLD}%s${RST} …\n\n" "$THEME"

# ── kitty color.conf ───────────────────────────────────────
apply_kitty() {
  mkdir -p "$(dirname "$KITTY_CONF")"
  cat > "$KITTY_CONF" <<EOF
# generated by theme-switch.sh — palette: $THEME
background            $bg
foreground            $bright
cursor                $accent
cursor_text_color     $bright

selection_background  $muted
selection_foreground  $text

# black
color0   $bg
color8   $border

# red
color1   #e64553
color9   #f38ba8

# green
color2   #40a02b
color10  #a6da95

# yellow
color3   #e5c890
color11  #eed49f

# blue
color4   #444444
color12  #555555

# magenta
color5   #444444
color13  #555555

# cyan
color6   #444444
color14  #555555

# white
color7   #999999
color15  #cccccc

active_tab_foreground   $bright
active_tab_background   $muted
inactive_tab_foreground #444
inactive_tab_background #999
EOF
  echo "  ✓ kitty   → $KITTY_CONF"
}

# ── neovim colors.lua ──────────────────────────────────────
apply_nvim() {
  mkdir -p "$(dirname "$NVIM_LUA")"
  cat > "$NVIM_LUA" <<EOF
-- generated by theme-switch.sh — palette: $THEME
local p = {
    bg      = "$bg",
    base    = "$base",
    surface = "$surface",
    overlay = "$overlay",
    border  = "$border",
    subtext = "$subtext",
    text    = "$text",
    bright  = "$bright",
    accent  = "$accent",
    muted   = "$muted",
}

local M = {}

function M.apply()
    local hl = vim.api.nvim_set_hl

    hl(0, "Normal",          { fg = p.text,    bg = p.bg })
    hl(0, "NormalNC",        { fg = p.subtext,  bg = p.bg })
    hl(0, "CursorLine",      { bg = p.base })
    hl(0, "Visual",          { bg = p.overlay })

    hl(0, "LineNr",          { fg = p.subtext,  bg = p.bg })
    hl(0, "SignColumn",      { fg = p.subtext,  bg = p.bg })
    hl(0, "CursorLineNr",    { fg = p.text,    bg = p.base })

    hl(0, "VertSplit",       { fg = p.border,   bg = p.bg })
    hl(0, "FloatBorder",     { fg = p.border,   bg = p.bg })
    hl(0, "NormalFloat",     { fg = p.text,    bg = p.base })

    hl(0, "StatusLine",      { fg = p.text,    bg = p.bg })
    hl(0, "StatusLineNC",    { fg = p.subtext,  bg = p.bg })

    -- Telescope
    hl(0, "TelescopeBorder",        { fg = p.border,  bg = p.bg })
    hl(0, "TelescopeNormal",        { fg = p.text,   bg = p.bg })
    hl(0, "TelescopePromptNormal",  { fg = p.text,   bg = p.base })
    hl(0, "TelescopePromptBorder",  { fg = p.border,  bg = p.base })
    hl(0, "TelescopePromptPrefix",  { fg = p.accent,  bg = p.base })
    hl(0, "TelescopeSelection",     { fg = p.text,   bg = p.overlay })
    hl(0, "TelescopeMatching",      { fg = p.accent,  bg = p.overlay })
    hl(0, "TelescopeResultsNormal", { fg = p.text,   bg = p.bg })
    hl(0, "TelescopePreviewNormal", { fg = p.text,   bg = p.bg })
    hl(0, "TelescopeResultsBorder", { fg = p.border,  bg = p.bg })
    hl(0, "TelescopePreviewBorder", { fg = p.border,  bg = p.bg })

    -- NvimTree
    hl(0, "NvimTreeNormal",           { fg = p.text,   bg = p.bg })
    hl(0, "NvimTreeNormalNC",         { fg = p.subtext, bg = p.bg })
    hl(0, "NvimTreeFolderName",       { fg = p.subtext })
    hl(0, "NvimTreeOpenedFolderName", { fg = p.text })
    hl(0, "NvimTreeFolderIcon",       { fg = p.subtext })
    hl(0, "NvimTreeOpenedFolderIcon", { fg = p.subtext })
    hl(0, "NvimTreeFileName",         { fg = p.text })
    hl(0, "NvimTreeExecFile",         { fg = p.accent })
    hl(0, "NvimTreeRootFolder",       { fg = p.bright, bold = true })
    hl(0, "NvimTreeIndentMarker",     { fg = p.border })
    hl(0, "NvimTreeGitDirty",         { fg = p.bright })
    hl(0, "NvimTreeGitNew",           { fg = p.accent })
    hl(0, "NvimTreeGitDeleted",       { fg = p.muted })
end

M.lualine_theme = {
    normal  = {
        a = { fg = p.text,    bg = p.bg },
        b = { fg = p.bright,  bg = p.bg },
        c = { fg = p.subtext, bg = p.bg },
    },
    insert  = { a = { fg = p.accent, bg = p.bg } },
    visual  = { a = { fg = p.accent, bg = p.bg } },
    replace = { a = { fg = p.bright, bg = p.bg } },
}

return M
EOF
  echo "  ✓ neovim  → $NVIM_LUA"
}

# ── gtk colors.css ─────────────────────────────────────────
apply_gtk() {
  mkdir -p "$(dirname "$GTK_CSS")"
  cat > "$GTK_CSS" <<EOF
/* generated by theme-switch.sh — palette: $THEME */
@define-color background   $bg;
@define-color base         $base;
@define-color surface      $surface;
@define-color overlay      $overlay;
@define-color border       $border;
@define-color subtext      $subtext;
@define-color text         $text;
@define-color bright       $bright;
@define-color accent       $accent;
@define-color accent_muted $muted;
EOF
  echo "  ✓ gtk     → $GTK_CSS"
}

# ── apply all ──────────────────────────────────────────────
apply_kitty
apply_nvim
apply_gtk

# ── live-reload kitty if running ───────────────────────────
if command -v kitty &>/dev/null && pgrep -x kitty &>/dev/null; then
  kitty @ set-colors --all --configured "$KITTY_CONF" 2>/dev/null \
    && echo "  ✓ kitty reloaded live"
fi

printf "\n  ${BOLD}done.${RST}  restart nvim / gtk apps to pick up the new colours.\n\n"
