#!/usr/bin/env bash
# Rofi-based theme switcher: pick a theme, apply colors everywhere, set a random wallpaper.

DOTTHEMES="$HOME/.config/dotthemes"
WALLPAPERS_DIR="$HOME/wallpapers"
JSON_SRC="$DOTTHEMES/colors.json"
KITTY_CONF="$HOME/.config/kitty/color.conf"
NVIM_LUA="$HOME/.config/nvim/lua/colors.lua"
WAYBAR_CSS="$HOME/.config/waybar/colors/colors.css"
ROFI_COLORS="$HOME/.config/rofi/colors.rasi"
STATE_DIR="$HOME/.config/hypr/state"
WALLPAPER_CACHE="$STATE_DIR/wallpaper"
THEME_CACHE="$STATE_DIR/theme"

command -v python3 &>/dev/null || { notify-send "Theme Switcher" "python3 is required"; exit 1; }
[[ -f "$JSON_SRC" ]] || { notify-send "Theme Switcher" "colors.json not found at $JSON_SRC"; exit 1; }

mkdir -p "$STATE_DIR"

# Extract palette rows: "Name|bg|base|surface|overlay|border|subtext|text|bright|accent|dim"
mapfile -t ROWS < <(python3 - "$JSON_SRC" <<'PY'
import json, sys
data = json.load(open(sys.argv[1]))
keys = ["true_black","vanta_ui","surface","elevated","border",
        "muted_text","body_text","bright_text","accent","accent_dim"]
for p in data:
    c = p["colors"]
    print(p["palette"] + "|" + "|".join(c[k]["hex"] for k in keys))
PY
)

mapfile -t NAMES < <(printf '%s\n' "${ROWS[@]}" | cut -d'|' -f1)

# Direct call or rofi picker
if [[ -n "$1" ]]; then
    THEME="$1"
else
    THEME=$(printf '%s\n' "${NAMES[@]}" | rofi -dmenu \
        -p "" \
        -mesg "Select a color theme" \
        -theme-str '
            window    { width: 520px; border-radius: 12px; }
            listview  { lines: 14; }
            element   { padding: 8px 14px; }
        ')
fi

[[ -z "$THEME" ]] && exit 0

# Find the palette row
for row in "${ROWS[@]}"; do
    IFS='|' read -r name bg base surface overlay border subtext text bright accent muted <<< "$row"
    [[ "$name" == "$THEME" ]] && break
done

[[ "$name" != "$THEME" ]] && { notify-send "Theme Switcher" "Unknown theme: $THEME"; exit 1; }

# ── Kitty ──────────────────────────────────────────────────────────────────────
mkdir -p "$(dirname "$KITTY_CONF")"
cat > "$KITTY_CONF" <<EOF
# generated by rofi-theme-switcher — palette: $THEME
background            $bg
foreground            $bright
cursor                $accent
cursor_text_color     $bright
selection_background  $muted
selection_foreground  $text
color0   $bg
color8   $border
color1   #e64553
color9   #f38ba8
color2   #40a02b
color10  #a6da95
color3   #e5c890
color11  #eed49f
color4   #444444
color12  #555555
color5   #444444
color13  #555555
color6   #444444
color14  #555555
color7   #999999
color15  #cccccc
active_tab_foreground   $bright
active_tab_background   $muted
inactive_tab_foreground #444
inactive_tab_background #999
EOF
pgrep -x kitty &>/dev/null && kitty @ set-colors --all --configured "$KITTY_CONF" 2>/dev/null

# ── Neovim ─────────────────────────────────────────────────────────────────────
mkdir -p "$(dirname "$NVIM_LUA")"
cat > "$NVIM_LUA" <<EOF
-- generated by rofi-theme-switcher — palette: $THEME
local p = {
    bg      = "$bg",
    base    = "$base",
    surface = "$surface",
    overlay = "$overlay",
    border  = "$border",
    subtext = "$subtext",
    text    = "$text",
    bright  = "$bright",
    accent  = "$accent",
    muted   = "$muted",
}
local M = {}
function M.apply()
    local hl = vim.api.nvim_set_hl
    hl(0, "Normal",          { fg = p.text,    bg = p.bg })
    hl(0, "NormalNC",        { fg = p.subtext,  bg = p.bg })
    hl(0, "CursorLine",      { bg = p.base })
    hl(0, "Visual",          { bg = p.overlay })
    hl(0, "LineNr",          { fg = p.subtext,  bg = p.bg })
    hl(0, "SignColumn",      { fg = p.subtext,  bg = p.bg })
    hl(0, "CursorLineNr",    { fg = p.text,    bg = p.base })
    hl(0, "VertSplit",       { fg = p.border,   bg = p.bg })
    hl(0, "FloatBorder",     { fg = p.border,   bg = p.bg })
    hl(0, "NormalFloat",     { fg = p.text,    bg = p.base })
    hl(0, "StatusLine",      { fg = p.text,    bg = p.bg })
    hl(0, "StatusLineNC",    { fg = p.subtext,  bg = p.bg })
    hl(0, "TelescopeBorder",        { fg = p.border,  bg = p.bg })
    hl(0, "TelescopeNormal",        { fg = p.text,   bg = p.bg })
    hl(0, "TelescopePromptNormal",  { fg = p.text,   bg = p.base })
    hl(0, "TelescopePromptBorder",  { fg = p.border,  bg = p.base })
    hl(0, "TelescopePromptPrefix",  { fg = p.accent,  bg = p.base })
    hl(0, "TelescopeSelection",     { fg = p.text,   bg = p.overlay })
    hl(0, "TelescopeMatching",      { fg = p.accent,  bg = p.overlay })
    hl(0, "TelescopeResultsNormal", { fg = p.text,   bg = p.bg })
    hl(0, "TelescopePreviewNormal", { fg = p.text,   bg = p.bg })
    hl(0, "TelescopeResultsBorder", { fg = p.border,  bg = p.bg })
    hl(0, "TelescopePreviewBorder", { fg = p.border,  bg = p.bg })
    hl(0, "NvimTreeNormal",           { fg = p.text,   bg = p.bg })
    hl(0, "NvimTreeNormalNC",         { fg = p.subtext, bg = p.bg })
    hl(0, "NvimTreeFolderName",       { fg = p.subtext })
    hl(0, "NvimTreeOpenedFolderName", { fg = p.text })
    hl(0, "NvimTreeFolderIcon",       { fg = p.subtext })
    hl(0, "NvimTreeOpenedFolderIcon", { fg = p.subtext })
    hl(0, "NvimTreeFileName",         { fg = p.text })
    hl(0, "NvimTreeExecFile",         { fg = p.accent })
    hl(0, "NvimTreeRootFolder",       { fg = p.bright, bold = true })
    hl(0, "NvimTreeIndentMarker",     { fg = p.border })
    hl(0, "NvimTreeGitDirty",         { fg = p.bright })
    hl(0, "NvimTreeGitNew",           { fg = p.accent })
    hl(0, "NvimTreeGitDeleted",       { fg = p.muted })
end
M.lualine_theme = {
    normal  = {
        a = { fg = p.text,    bg = p.bg },
        b = { fg = p.bright,  bg = p.bg },
        c = { fg = p.subtext, bg = p.bg },
    },
    insert  = { a = { fg = p.accent, bg = p.bg } },
    visual  = { a = { fg = p.accent, bg = p.bg } },
    replace = { a = { fg = p.bright, bg = p.bg } },
}
return M
EOF

# ── Waybar ─────────────────────────────────────────────────────────────────────
mkdir -p "$(dirname "$WAYBAR_CSS")"
cat > "$WAYBAR_CSS" <<EOF
/* generated by rofi-theme-switcher — palette: $THEME */
@define-color background   $bg;
@define-color base         $base;
@define-color surface      $surface;
@define-color overlay      $overlay;
@define-color border       $border;
@define-color subtext      $subtext;
@define-color text         $text;
@define-color bright       $bright;
@define-color accent       $accent;
@define-color accent_muted $muted;
EOF

# ── Rofi colors ────────────────────────────────────────────────────────────────
mkdir -p "$(dirname "$ROFI_COLORS")"
cat > "$ROFI_COLORS" <<EOF
/* generated by rofi-theme-switcher — palette: $THEME */
* {
    bg:         $surface;
    bg-alt:     $overlay;
    border-col: $border;
    fg:         $text;
    fg-bright:  $bright;
    accent:     $accent;
    accent-dim: $muted;
    urgent:     #dc5050;
}
EOF

# ── Hyprland borders (live, no reload) ─────────────────────────────────────────
accent_hex="${accent#\#}"
muted_hex="${muted#\#}"
hyprctl keyword general:col.active_border   "rgba(${accent_hex}ff)" 2>/dev/null
hyprctl keyword general:col.inactive_border "rgba(${muted_hex}33)"  2>/dev/null

# ── Reload Waybar ──────────────────────────────────────────────────────────────
pkill -SIGUSR2 waybar 2>/dev/null

# ── Save state ─────────────────────────────────────────────────────────────────
echo "$THEME"   > "$THEME_CACHE"
echo "$accent"  > "$STATE_DIR/accent"
echo "$muted"   > "$STATE_DIR/accent_dim"

# ── Set random wallpaper from theme directory ───────────────────────────────────
DIR_NAME="${THEME// /_}"
THEME_WALL_DIR="$WALLPAPERS_DIR/$DIR_NAME"

if [[ -d "$THEME_WALL_DIR" ]]; then
    mapfile -t walls < <(find "$THEME_WALL_DIR" -maxdepth 1 -type f \
        \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' \
           -o -iname '*.webp' -o -iname '*.bmp' \))
    if [[ ${#walls[@]} -gt 0 ]]; then
        WALL="${walls[RANDOM % ${#walls[@]}]}"
        swww img "$WALL" --transition-type fade --transition-duration 1
        echo "$WALL" > "$WALLPAPER_CACHE"
        notify-send "Theme" "$THEME" -h string:x-canonical-private-synchronous:theme 2>/dev/null
        exit 0
    fi
fi

notify-send "Theme" "$THEME applied (no wallpapers in ~/wallpapers/$DIR_NAME)" 2>/dev/null
