#!/usr/bin/env bash
# Rofi-based theme switcher: pick a theme, apply colors everywhere, set a random wallpaper.

DOTTHEMES="$HOME/.config/dotthemes"
WALLPAPERS_DIR="$HOME/wallpapers"
JSON_SRC="$DOTTHEMES/colors.json"
KITTY_CONF="$HOME/.config/kitty/color.conf"
NVIM_LUA="$HOME/.config/nvim/lua/theme.lua"
WAYBAR_CSS="$HOME/.config/waybar/colors/colors.css"
ROFI_COLORS="$HOME/.config/rofi/colors.rasi"
GTK3_CSS="$HOME/.config/gtk-3.0/gtk.css"
GTK4_CSS="$HOME/.config/gtk-4.0/gtk.css"
STATE_DIR="$HOME/.config/hypr/state"
WALLPAPER_CACHE="$STATE_DIR/wallpaper"
THEME_CACHE="$STATE_DIR/theme"
LOCAL_CACHE_DIR="$HOME/.cache/hypr/wallpapers"

command -v python3 &>/dev/null || { notify-send "Theme Switcher" "python3 is required"; exit 1; }
[[ -f "$JSON_SRC" ]] || { notify-send "Theme Switcher" "colors.json not found at $JSON_SRC"; exit 1; }

mkdir -p "$STATE_DIR"

# Extract palette rows: "Name|bg|base|surface|overlay|border|subtext|text|bright|accent|dim"
mapfile -t ROWS < <(python3 - "$JSON_SRC" <<'PY'
import json, sys
data = json.load(open(sys.argv[1]))
keys = ["true_black","vanta_ui","surface","elevated","border",
        "muted_text","body_text","bright_text","accent","accent_dim"]
for p in data:
    c = p["colors"]
    print(p["palette"] + "|" + "|".join(c[k]["hex"] for k in keys))
PY
)

mapfile -t NAMES < <(printf '%s\n' "${ROWS[@]}" | cut -d'|' -f1)

# Direct call or rofi picker
if [[ -n "$1" ]]; then
    THEME="$1"
else
    THEME=$(printf '%s\n' "${NAMES[@]}" | rofi -dmenu \
        -matching fuzzy \
        -sort \
        -sorting-method fzf \
        -p "󰔏 " \
        -theme "$HOME/.config/rofi/theme-picker.rasi")
fi

[[ -z "$THEME" ]] && exit 0

# Find the palette row
for row in "${ROWS[@]}"; do
    IFS='|' read -r name bg base surface overlay border subtext text bright accent muted <<< "$row"
    [[ "$name" == "$THEME" ]] && break
done

[[ "$name" != "$THEME" ]] && { notify-send "Theme Switcher" "Unknown theme: $THEME"; exit 1; }

# ── Kitty ──────────────────────────────────────────────────────────────────────
mkdir -p "$(dirname "$KITTY_CONF")"
cat > "$KITTY_CONF" <<EOF
# generated by rofi-theme-switcher — palette: $THEME
background            $bg
foreground            $bright
cursor                $accent
cursor_text_color     $bright
selection_background  $muted
selection_foreground  $text
color0   $bg
color8   $border
color1   #e64553
color9   #f38ba8
color2   #40a02b
color10  #a6da95
color3   #e5c890
color11  #eed49f
color4   #444444
color12  #555555
color5   #444444
color13  #555555
color6   #444444
color14  #555555
color7   #999999
color15  #cccccc
active_tab_foreground   $bright
active_tab_background   $muted
inactive_tab_foreground #444
inactive_tab_background #999
EOF
pgrep -x kitty &>/dev/null && kitty @ set-colors --all --configured "$KITTY_CONF" 2>/dev/null

# ── Neovim palette (theme.lua only — colors.lua is not touched) ────────────────
mkdir -p "$(dirname "$NVIM_LUA")"
cat > "$NVIM_LUA" <<EOF
-- generated by rofi-theme-switcher — palette: $THEME
local p = {
    bg      = "$bg",
    base    = "$base",
    surface = "$surface",
    overlay = "$overlay",
    border  = "$border",
    subtext = "$subtext",
    text    = "$text",
    bright  = "$bright",
    accent  = "$accent",
    muted   = "$muted",
}
return p
EOF

# ── Waybar ─────────────────────────────────────────────────────────────────────
mkdir -p "$(dirname "$WAYBAR_CSS")"
cat > "$WAYBAR_CSS" <<EOF
/* generated by rofi-theme-switcher — palette: $THEME */
@define-color background   $bg;
@define-color base         $base;
@define-color surface      $surface;
@define-color overlay      $overlay;
@define-color border       $border;
@define-color subtext      $subtext;
@define-color text         $text;
@define-color bright       $bright;
@define-color accent       $accent;
@define-color accent_muted $muted;
EOF

# ── Rofi colors ────────────────────────────────────────────────────────────────
mkdir -p "$(dirname "$ROFI_COLORS")"
cat > "$ROFI_COLORS" <<EOF
/* generated by rofi-theme-switcher — palette: $THEME */
* {
    bg:         $surface;
    bg-alt:     $overlay;
    border-col: $border;
    fg:         $text;
    fg-bright:  $bright;
    accent:     $accent;
    accent-dim: $muted;
    urgent:     #dc5050;
}
EOF

# ── GTK3 ───────────────────────────────────────────────────────────────────────
mkdir -p "$(dirname "$GTK3_CSS")"
cat > "$GTK3_CSS" <<EOF
/* generated by rofi-theme-switcher — palette: $THEME */
@define-color theme_bg_color         $bg;
@define-color theme_base_color       $base;
@define-color theme_fg_color         $text;
@define-color theme_text_color       $bright;
@define-color theme_selected_bg_color $accent;
@define-color theme_selected_fg_color $bg;
@define-color theme_unfocused_bg_color $bg;
@define-color theme_unfocused_fg_color $subtext;
@define-color borders                $border;
@define-color unfocused_borders      $border;
EOF

# ── GTK4 / libadwaita ──────────────────────────────────────────────────────────
mkdir -p "$(dirname "$GTK4_CSS")"
cat > "$GTK4_CSS" <<EOF
/* generated by rofi-theme-switcher — palette: $THEME */
@define-color window_bg_color        $bg;
@define-color window_fg_color        $bright;
@define-color view_bg_color          $base;
@define-color view_fg_color          $text;
@define-color accent_color           $accent;
@define-color accent_bg_color        $accent;
@define-color accent_fg_color        $bg;
@define-color sidebar_bg_color       $base;
@define-color sidebar_fg_color       $text;
@define-color headerbar_bg_color     $base;
@define-color headerbar_fg_color     $bright;
@define-color card_bg_color          $surface;
@define-color card_fg_color          $text;
@define-color popover_bg_color       $surface;
@define-color popover_fg_color       $text;
@define-color shade_color            rgba(0,0,0,0.36);
@define-color scrollbar_outline_color rgba(0,0,0,0.5);
EOF

gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark' 2>/dev/null
gsettings set org.gnome.desktop.interface gtk-theme 'Adwaita' 2>/dev/null

# ── Hyprland borders (live, no reload) ─────────────────────────────────────────
accent_hex="${accent#\#}"
muted_hex="${muted#\#}"
hyprctl keyword general:col.active_border   "rgba(${accent_hex}ff)" 2>/dev/null
hyprctl keyword general:col.inactive_border "rgba(${muted_hex}33)"  2>/dev/null

# ── Reload Waybar ──────────────────────────────────────────────────────────────
pkill -SIGUSR2 waybar 2>/dev/null

# ── Save state ─────────────────────────────────────────────────────────────────
echo "$THEME"   > "$THEME_CACHE"
echo "$accent"  > "$STATE_DIR/accent"
echo "$muted"   > "$STATE_DIR/accent_dim"

# ── Set random wallpaper from theme directory ───────────────────────────────────
DIR_NAME="${THEME// /_}"
THEME_WALL_DIR="$WALLPAPERS_DIR/$DIR_NAME"
# Case-insensitive fallback if direct lookup misses
[[ ! -d "$THEME_WALL_DIR" ]] && \
    THEME_WALL_DIR=$(find "$WALLPAPERS_DIR" -maxdepth 1 -type d -iname "$DIR_NAME" | head -1)

if [[ -n "$THEME_WALL_DIR" && -d "$THEME_WALL_DIR" ]]; then
    mapfile -t walls < <(find "$THEME_WALL_DIR" -maxdepth 1 -type f \
        \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' \
           -o -iname '*.webp' -o -iname '*.bmp' \))
    if [[ ${#walls[@]} -gt 0 ]]; then
        WALL="${walls[RANDOM % ${#walls[@]}]}"
        awww img "$WALL" --transition-type fade --transition-duration 1
        # Cache a local copy so the wallpaper works offline
        mkdir -p "$LOCAL_CACHE_DIR"
        CACHED_WALL="$LOCAL_CACHE_DIR/${DIR_NAME}_$(basename "$WALL")"
        cp -- "$WALL" "$CACHED_WALL"
        echo "$CACHED_WALL" > "$WALLPAPER_CACHE"
        notify-send "Theme" "$THEME" -h string:x-canonical-private-synchronous:theme 2>/dev/null
        exit 0
    fi
fi

notify-send "Theme" "$THEME applied (no wallpapers in ~/wallpapers/$DIR_NAME)" 2>/dev/null
